// Lists every file in dist/ and builds it from tokens.json and the vendored fonts. gen.js writes the
// output; the tests check the committed dist/ still matches it.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { loadFont } from './font.js';
import {
	ICON_FRAC,
	banner,
	coloursFrom,
	favicon16,
	favicon32,
	mark,
	onDark,
	onLight,
	tile,
	wordmark
} from './logo.js';
import { encodePNG, ico } from './png.js';
import { render } from './raster.js';
import { svg } from './scene.js';
import { parseTokens } from './tokens.js';

// Paths within the repo.
export const TOKENS_FILE = 'tokens.json';
export const FONT_FILES = {
	regular: 'fonts/Sora-Regular.ttf',
	light: 'fonts/Sora-Light.ttf',
	extraLight: 'fonts/Sora-ExtraLight.ttf'
};
export const DIST_DIR = 'dist';
const WEB_FONTS_DIR = 'fonts/web';

// The web fonts dist/fonts.css declares, with the weights each page can use.
const WEB_FONTS = [{ family: 'Sora', file: 'sora', weights: [200, 300, 400, 500, 600] }];

/** Reads what build needs from the repo at root. */
export function readSources(root) {
	const webFonts = join(root, WEB_FONTS_DIR);
	return {
		tokensJSON: readFileSync(join(root, TOKENS_FILE), 'utf8'),
		fontData: Object.fromEntries(
			Object.entries(FONT_FILES).map(([key, file]) => [key, readFileSync(join(root, file))])
		),
		webFonts: new Map(readdirSync(webFonts).map((n) => [n, readFileSync(join(webFonts, n))]))
	};
}

/** Renders every asset. Returns a Map of path under dist/ to Buffer. */
export function build({ tokensJSON, fontData, webFonts }) {
	const tokens = parseTokens(tokensJSON);
	const c = coloursFrom(tokens.logo);
	const fonts = Object.fromEntries(
		Object.entries(fontData).map(([key, data]) => [key, loadFont(data)])
	);
	const appIcon = tile(c, ICON_FRAC, 'Rogue Keyboards');
	const discord = tile(c, ICON_FRAC, 'Rogue Keyboards Discord avatar');
	const twitch = banner(fonts, c, 1200, 480, 520, 'Rogue Keyboards Twitch profile banner');
	const player = banner(fonts, c, 1920, 1080, 760, 'Rogue Keyboards Twitch video player banner');
	const scenes = {
		wordmarkOnDark: wordmark(fonts, onDark(c)),
		wordmarkOnLight: wordmark(fonts, onLight(c)),
		markOnDark: mark(onDark(c)),
		markOnLight: mark(onLight(c))
	};

	const files = new Map([['tokens.css', Buffer.from(tokensCSS(tokens))]]);

	const svgs = {
		'wordmark-on-dark.svg': scenes.wordmarkOnDark,
		'wordmark-on-light.svg': scenes.wordmarkOnLight,
		'mark-on-dark.svg': scenes.markOnDark,
		'mark-on-light.svg': scenes.markOnLight,
		'favicon.svg': favicon32(c),
		'discord-avatar.svg': discord,
		'twitch-banner.svg': twitch,
		'twitch-player-banner.svg': player
	};
	for (const [name, scene] of Object.entries(svgs)) {
		files.set(name, Buffer.from(svg(scene)));
	}

	const pngs = [
		['wordmark-on-dark.png', scenes.wordmarkOnDark, 1200],
		['wordmark-on-light.png', scenes.wordmarkOnLight, 1200],
		['mark-on-dark.png', scenes.markOnDark, 512],
		['mark-on-light.png', scenes.markOnLight, 512],
		['favicon-16.png', favicon16(c), 16],
		['favicon-32.png', favicon32(c), 32],
		['apple-touch-icon.png', appIcon, 180],
		['icon-192.png', appIcon, 192],
		['icon-512.png', appIcon, 512],
		['discord-avatar.png', discord, 1024],
		['twitch-banner.png', twitch, 1200],
		['twitch-player-banner.png', player, 1920]
	];
	for (const [name, scene, px] of pngs) {
		files.set(name, encodePNG(render(scene, px)));
	}

	const favicon48 = encodePNG(render(favicon32(c), 48)); // only needed inside the .ico
	files.set(
		'favicon.ico',
		ico(files.get('favicon-16.png'), files.get('favicon-32.png'), favicon48)
	);

	files.set('fonts.css', Buffer.from(fontsCSS()));
	for (const [name, data] of webFonts) {
		files.set(`fonts/${name}`, data);
	}
	return files;
}

// Declares the web fonts, with URLs relative to dist/fonts.css, so a bundler resolves them.
function fontsCSS() {
	const faces = WEB_FONTS.flatMap(({ family, file, weights }) =>
		weights.map(
			(weight) =>
				`@font-face {\n\tfont-family: '${family}';\n\tfont-style: normal;\n\tfont-display: swap;\n` +
				`\tfont-weight: ${weight};\n\tsrc: url('./fonts/${file}-latin-${weight}.woff2') format('woff2');\n}\n`
		)
	);
	return `/* Generated by \`mise run gen\`. Do not edit. Licensed under the SIL Open Font License; see fonts/. */\n${faces.join('\n')}`;
}

// Renders the tokens as CSS custom properties: theme tokens under their own names (--accent), logo
// colours prefixed (--logo-amber).
function tokensCSS({ logo, theme }) {
	const lines = (palette, prefix) =>
		palette.map(({ name, value }) => `\t--${prefix}${name}: ${value};\n`).join('');
	return (
		'/* Generated from tokens.json by `mise run gen`. Do not edit. */\n:root {\n' +
		`${lines(theme, '')}\n${lines(logo, 'logo-')}}\n`
	);
}
